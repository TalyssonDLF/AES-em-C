static const uint8_t rcon[11] = {
    0x8d,0x01,0x02,0x04,0x08,0x10,0x20,0x40,0x80,0x1b,0x36
};

static void xor_blocks(uint8_t *dst, const uint8_t *a, const uint8_t *b) {
    for (int i = 0; i < AES_BLOCK_SIZE; i++)
        dst[i] = a[i] ^ b[i];
}

static void rot_word(uint8_t *word) {
    uint8_t tmp = word[0];
    word[0] = word[1]; word[1] = word[2]; word[2] = word[3]; word[3] = tmp;
}

static void sub_word(uint8_t *word) {
    word[0] = sbox[word[0]]; word[1] = sbox[word[1]];
    word[2] = sbox[word[2]]; word[3] = sbox[word[3]];
}

static void key_expansion(const uint8_t *key, uint8_t *round_keys) {
    int i;
    uint8_t tmp[4];
    memcpy(round_keys, key, AES_KEY_SIZE);
    for (i = 8; i < 60; i++) {
        memcpy(tmp, round_keys + (i - 1) * 4, 4);
        if (i % 8 == 0) { rot_word(tmp); sub_word(tmp); tmp[0] ^= rcon[i / 8]; }
        else if (i % 8 == 4) { sub_word(tmp); }
        round_keys[i*4+0] = round_keys[(i-8)*4+0] ^ tmp[0];
        round_keys[i*4+1] = round_keys[(i-8)*4+1] ^ tmp[1];
        round_keys[i*4+2] = round_keys[(i-8)*4+2] ^ tmp[2];
        round_keys[i*4+3] = round_keys[(i-8)*4+3] ^ tmp[3];
    }
}

static void sub_bytes(uint8_t *state) {
    for (int i = 0; i < AES_BLOCK_SIZE; i++) state[i] = sbox[state[i]];
}

static void inv_sub_bytes(uint8_t *state) {
    for (int i = 0; i < AES_BLOCK_SIZE; i++) state[i] = rsbox[state[i]];
}

static void shift_rows(uint8_t *state) {
    uint8_t tmp;
    tmp=state[1]; state[1]=state[5]; state[5]=state[9]; state[9]=state[13]; state[13]=tmp;
    tmp=state[2]; state[2]=state[10]; state[10]=tmp;
    tmp=state[6]; state[6]=state[14]; state[14]=tmp;
    tmp=state[15]; state[15]=state[11]; state[11]=state[7]; state[7]=state[3]; state[3]=tmp;
}

static void inv_shift_rows(uint8_t *state) {
    uint8_t tmp;
    tmp=state[13]; state[13]=state[9]; state[9]=state[5]; state[5]=state[1]; state[1]=tmp;
    tmp=state[2]; state[2]=state[10]; state[10]=tmp;
    tmp=state[6]; state[6]=state[14]; state[14]=tmp;
    tmp=state[3]; state[3]=state[7]; state[7]=state[11]; state[11]=state[15]; state[15]=tmp;
}

static uint8_t gmul(uint8_t a, uint8_t b) {
    uint8_t p = 0;
    while (b) {
        if (b & 1) p ^= a;
        a = (a << 1) ^ (a & 0x80 ? 0x1b : 0x00);
        b >>= 1;
    }
    return p;
}

static void mix_columns(uint8_t *state) {
    uint8_t tmp[4];
    for (int col = 0; col < 4; col++) {
        uint8_t *c = state + col * 4;
        tmp[0] = gmul(0x02,c[0])^gmul(0x03,c[1])^c[2]          ^c[3];
        tmp[1] = c[0]           ^gmul(0x02,c[1])^gmul(0x03,c[2])^c[3];
        tmp[2] = c[0]           ^c[1]           ^gmul(0x02,c[2])^gmul(0x03,c[3]);
        tmp[3] = gmul(0x03,c[0])^c[1]           ^c[2]           ^gmul(0x02,c[3]);
        memcpy(c, tmp, 4);
    }
}

static void inv_mix_columns(uint8_t *state) {
    uint8_t tmp[4];
    for (int col = 0; col < 4; col++) {
        uint8_t *c = state + col * 4;
        tmp[0] = gmul(0x0e,c[0])^gmul(0x0b,c[1])^gmul(0x0d,c[2])^gmul(0x09,c[3]);
        tmp[1] = gmul(0x09,c[0])^gmul(0x0e,c[1])^gmul(0x0b,c[2])^gmul(0x0d,c[3]);
        tmp[2] = gmul(0x0d,c[0])^gmul(0x09,c[1])^gmul(0x0e,c[2])^gmul(0x0b,c[3]);
        tmp[3] = gmul(0x0b,c[0])^gmul(0x0d,c[1])^gmul(0x09,c[2])^gmul(0x0e,c[3]);
        memcpy(c, tmp, 4);
    }
}

static void add_round_key(uint8_t *state, const uint8_t *round_key) {
    for (int i = 0; i < AES_BLOCK_SIZE; i++) state[i] ^= round_key[i];
}

static void aes_encrypt_block(const uint8_t *in, uint8_t *out, const uint8_t *rk) {
    uint8_t state[16];
    memcpy(state, in, 16);
    add_round_key(state, rk);
    for (int r = 1; r <= 13; r++) {
        sub_bytes(state); shift_rows(state); mix_columns(state);
        add_round_key(state, rk + r * AES_BLOCK_SIZE);
    }
    sub_bytes(state); shift_rows(state);
    add_round_key(state, rk + 14 * AES_BLOCK_SIZE);
    memcpy(out, state, 16);
}

static void aes_decrypt_block(const uint8_t *in, uint8_t *out, const uint8_t *rk) {
    uint8_t state[16];
    memcpy(state, in, 16);
    add_round_key(state, rk + 14 * AES_BLOCK_SIZE);
    for (int r = 13; r >= 1; r--) {
        inv_shift_rows(state); inv_sub_bytes(state);
        add_round_key(state, rk + r * AES_BLOCK_SIZE);
        inv_mix_columns(state);
    }
    inv_shift_rows(state); inv_sub_bytes(state);
    add_round_key(state, rk);
    memcpy(out, state, 16);
}

static int pkcs7_pad(const uint8_t *in, size_t in_len, uint8_t *out) {
    int pad = AES_BLOCK_SIZE - (in_len % AES_BLOCK_SIZE);
    memcpy(out, in, in_len);
    memset(out + in_len, pad, pad);
    return in_len + pad;
}

static int pkcs7_unpad(uint8_t *data, int len) {
    int pad = data[len - 1];
    if (pad < 1 || pad > 16) return -1;
    return len - pad;
}

int aes256_encrypt(const uint8_t *key, const uint8_t *iv,
                   const uint8_t *plain, size_t plain_len, uint8_t *out) {
    uint8_t rk[AES_KEY_EXP_SIZE];
    key_expansion(key, rk);
    memcpy(out, iv, AES_BLOCK_SIZE);
    out += AES_BLOCK_SIZE;
    uint8_t padded[4096];
    int padded_len = pkcs7_pad(plain, plain_len, padded);
    uint8_t prev[AES_BLOCK_SIZE];
    memcpy(prev, iv, AES_BLOCK_SIZE);
    for (int i = 0; i < padded_len; i += AES_BLOCK_SIZE) {
        uint8_t block[AES_BLOCK_SIZE];
        xor_blocks(block, padded + i, prev);
        aes_encrypt_block(block, out + i, rk);
        memcpy(prev, out + i, AES_BLOCK_SIZE);
    }
    return AES_BLOCK_SIZE + padded_len;
}

int aes256_decrypt(const uint8_t *key, const uint8_t *cipher,
                   size_t cipher_len, uint8_t *out) {
    uint8_t rk[AES_KEY_EXP_SIZE];
    key_expansion(key, rk);
    uint8_t prev[AES_BLOCK_SIZE];
    memcpy(prev, cipher, AES_BLOCK_SIZE);
    cipher += AES_BLOCK_SIZE;
    cipher_len -= AES_BLOCK_SIZE;
    for (size_t i = 0; i < cipher_len; i += AES_BLOCK_SIZE) {
        uint8_t block[AES_BLOCK_SIZE];
        aes_decrypt_block(cipher + i, block, rk);
        xor_blocks(out + i, block, prev);
        memcpy(prev, cipher + i, AES_BLOCK_SIZE);
    }
    return pkcs7_unpad(out, cipher_len);
}

static void random_iv(uint8_t *iv) {
    FILE *f = fopen("/dev/urandom", "rb");
    if (!f) { perror("urandom"); exit(1); }
    fread(iv, 1, AES_BLOCK_SIZE, f);
    fclose(f);
}

static void bytes_to_hex(const uint8_t *data, int len, char *out) {
    for (int i = 0; i < len; i++) sprintf(out + i * 2, "%02x", data[i]);
    out[len * 2] = '\0';
}

static int hex_to_bytes(const char *hex, uint8_t *out) {
    int len = strlen(hex) / 2;
    for (int i = 0; i < len; i++) sscanf(hex + i * 2, "%02hhx", &out[i]);
    return len;
}

int main(int argc, char *argv[]) {
    if (argc != 4) {
        printf("Uso:\n");
        printf("  Encriptar: %s enc \"texto\" \"senha32bytes\"\n", argv[0]);
        printf("  Decriptar: %s dec <hex>  \"senha32bytes\"\n", argv[0]);
        return 1;
    }

    char *modo = argv[1], *input = argv[2], *senha = argv[3];
    uint8_t key[AES_KEY_SIZE] = {0};
    strncpy((char *)key, senha, AES_KEY_SIZE);

    if (strcmp(modo, "enc") == 0) {
        uint8_t iv[AES_BLOCK_SIZE];
        random_iv(iv);
        uint8_t out[4096];
        int out_len = aes256_encrypt(key, iv, (uint8_t *)input, strlen(input), out);
        char hex[8192];
        bytes_to_hex(out, out_len, hex);
        printf("Encriptado (hex):\n%s\n", hex);

    } else if (strcmp(modo, "dec") == 0) {
        uint8_t cipher[4096];
        int cipher_len = hex_to_bytes(input, cipher);
        uint8_t out[4096] = {0};
        int out_len = aes256_decrypt(key, cipher, cipher_len, out);
        if (out_len < 0) { printf("Erro: senha incorreta ou dados corrompidos!\n"); return 1; }
        printf("Decriptado:\n%.*s\n", out_len, out);

    } else {
        printf("Modo invalido! Use 'enc' ou 'dec'\n");
        return 1;
    }
    return 0;
}